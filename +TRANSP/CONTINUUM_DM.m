function dm = CONTINUUM_DM(npp, dg, dpp1, variant)
% "CONTINUUM_DM" returns continuum regime mobility diameters of fractal...
%   ...aggregates from the backbone relations of reference 8 of the...
%   ...README, as the ratio beta = Rm / Rg of the mobility and gyration...
%   ...radii times the gyration diameter.
% ----------------------------------------------------------------------- %
%
% Inputs:
%     npp: Number of primaries in each aggregate
%     dg: Gyration diameter of each aggregate (m), with the gyration of...
%         ...the primaries included (PAR.GYRATION)
%     dpp1: Primary diameter of each single-primary aggregate (m), used...
%         ...by 'backbone' only, one entry per aggregate (any value for...
%         ...npp > 1)
%     variant: 'eq17' (Eq. 17 at every N)...
%         ...or 'backbone' (Eq. 17 up to the crossover, Eqs. 18a and 18b...
%         ...at the ends)
% ----------------------------------------------------------------------- %
%
% Output:
%     dm: Continuum regime mobility diameter (m)
% ----------------------------------------------------------------------- %
%
% 'eq17'. beta = 1.29 N^-0.13 at every N (Eq. 17, p. 769, proposed for...
%     ...small N up to N = 100).
% 'backbone'. N = 1 gives dm = dpp1, the sphere itself. N = 2 gives...
%     ...beta = 2^0.46 / sqrt(1.6), which turns Eq. 18a (Rm = a N^0.46,...
%     ...p. 771) into dm = 2^0.46 dp for two touching equal spheres,...
%     ...whose gyration radius is sqrt(1.6) a (beta = 1.0875, the known...
%     ...doublet value 1.09 of p. 770). 3 <= N <= 74 uses Eq. 17. N > 74...
%     ...uses beta = 0.75, the ratio that Eq. 18b (Rm = 0.65 a N^0.56)...
%     ...gives for Df = 1.78 and kf = 1.3 (p. 771). The crossover N = 74...
%     ...is where Eqs. 18a and 18b meet (p. 771).
% Step at the crossover. beta goes from 0.7372 (Eq. 17 at N = 74) to...
%     ...0.75 at N = 75, so dm jumps by 1.735 percent for the same...
%     ...gyration diameter. The crossover is kept at N = 74, where the...
%     ...two backbone relations meet. Eq. 17 reaches 0.75 at N = 64.8, a...
%     ...continuous join would move the crossover there.
% Range. beta = 0.75 is the large-N ratio of DLCA aggregates (0.75 +/-...
%     ...0.05, p. 771, RLCA aggregates have 0.97). It is used as the...
%     ...selected approximation for every aggregate above N = 74, so...
%     ...aggregates of other morphology and the doublet relation applied...
%     ...to unequal or separated primaries are extrapolations of these...
%     ...relations, not relations established for them.
% Inputs may be rows or columns, dm is a column with one entry per...
%     ...aggregate.
% ----------------------------------------------------------------------- %

n_cross = 74; % Largest N of the small-N backbone (p. 771)
if numel(npp) ~= numel(dg)
    error('sootMosaic:CONTINUUM_DM:SizeMismatch', ['npp and dg must ', ...
        'hold one value per aggregate each.'])
end
npp = npp(:);
dg = dg(:);

switch variant
    case 'eq17'
        dm = 1.29 * npp.^(-0.13) .* dg;
    case 'backbone'
        if numel(dpp1) ~= numel(npp)
            error('sootMosaic:CONTINUUM_DM:SizeMismatch', ['dpp1 must ', ...
                'hold one value per aggregate under backbone.'])
        end
        beta = 1.29 * npp.^(-0.13); % Eq. 17
        beta(npp == 2) = 2^0.46 / sqrt(1.6); % Eq. 18a for a doublet
        beta(npp > n_cross) = 0.75; % Eq. 18b for Df 1.78 and kf 1.3
        dpp1 = dpp1(:);
        dm = beta .* dg;
        ind_1 = (npp == 1);
        if any(ind_1)
            dm(ind_1) = dpp1(ind_1); % A single sphere moves as itself
        end
    otherwise
        error('sootMosaic:CONTINUUM_DM:UnknownVariant', ['Unknown ', ...
            'variant %s. Known variants are eq17 and backbone.'], variant)
end

end
