function result = MASS(grid, states, relation, cfg, options)
% "MASS" integrates the mass concentration of a number distribution.
% ----------------------------------------------------------------------- %
%
% Inputs:
%     grid: One-dimensional log INV.Grid of mobility diameters for a...
%         ...power law, or of aerodynamic diameters for pairs (nm)
%     states: dN/dlog10(d) at the grid cells, one column (cm^-3)
%     relation: Structure with form power_law or pairs and calibrated_1,...
%         ...true when the densities behind it already carry k(dm)....
%         ...power_law: rho_ref_kg_m3 at dm_ref_nm with the mass-mobility...
%         ...exponent and an optional 2 x 2 covariance of log10 rho_ref and...
%         ...the exponent, real, symmetric and positive semidefinite....
%         ...pairs: dm_nm per grid cell with the AAC...
%         ...temperature_k and pressure_pa of the (da, dm) pairs
%     cfg: Resolved +INV configuration
%     options: Optional covariance_cm6 of states (cm^-6), real, symmetric...
%         ...and positive semidefinite
% ----------------------------------------------------------------------- %
%
% Outputs:
%     result: Mass concentration with its number, relation and calibration...
%         ...uncertainty terms (NaN when none is available), the mass per...
%         ...cell, k(dm) with its range flags, the mass share outside the...
%         ...calibrated range and the k(dm) provenance (ug/m3)
% ----------------------------------------------------------------------- %
% Method: log quadrature of (pi/6) rho_eff dm^3 over dN/dlog10 d;...
%     ...Tavakoli and Olfert (2014, Eqs. 3-5 and 7), particle mass from...
%     ...a (da, dm) pair through INV.RHO_EFF; Kiasadegh et al. (2026,...
%     ...Eqs. 33 and 34), k(dm) applied once through INV.CALIB_K.
% Reimplementation. The quadrature is the midpoint rule on the grid cells....
%     ...Uncertainty terms are linear propagation of the state covariance...
%     ...through INV.DELTA_PROP, of the power-law covariance and of the...
%     ...relative k(dm) uncertainty, the last one shared by every cell.
%     ...The total combines the terms that are available.

if nargin < 5 || isempty(options), options = struct(); end
if ~isstruct(options) || ~isscalar(options) || ...
        any(~ismember(fieldnames(options), {'covariance_cm6'}))
    fail('Options', 'Unknown mass option.');
end
if ~isa(grid, 'INV.Grid') || grid.dim ~= 1 || ...
        ~strcmp(grid.discrete, 'log')
    fail('Grid', 'Require a one-dimensional log INV.Grid (nm).');
end
if ~isnumeric(states) || ~isreal(states) || ~iscolumn(states) || ...
        numel(states) ~= grid.Ne || any(~isfinite(states)) || ...
        any(states < 0)
    fail('States', 'Require one nonnegative column per grid cell (cm^-3).');
end
if ~isstruct(relation) || ~isscalar(relation) || ...
        ~isfield(relation, 'form') || ~isfield(relation, 'calibrated_1') || ...
        ~islogical(relation.calibrated_1) || ~isscalar(relation.calibrated_1)
    fail('Relation', 'Require form and a logical calibrated_1.');
end
d_m = grid.elements(:) * 1e-9;
[~, width] = grid.dr();
to_ugm3 = 1e6 * 1e9; % cm^-3 to m^-3 and kg to ug
theta_jacobian = [];
switch relation.form
    case 'power_law'
        required = {'rho_ref_kg_m3', 'dm_ref_nm', 'exponent'};
        if ~all(isfield(relation, required)) || ...
                ~positive(relation.rho_ref_kg_m3) || ...
                ~positive(relation.dm_ref_nm) || ...
                ~isnumeric(relation.exponent) || ...
                ~isscalar(relation.exponent) || ~isfinite(relation.exponent)
            fail('Relation', ...
                'A power law needs rho_ref_kg_m3, dm_ref_nm and exponent.');
        end
        coordinate = 'mobility';
        dm_m = d_m;
        ratio = dm_m / (relation.dm_ref_nm * 1e-9);
        rho = relation.rho_ref_kg_m3 * ratio .^ (relation.exponent - 3);
        % Derivatives of ln(rho) in log10(rho_ref) and in the exponent
        theta_jacobian = [log(10) * ones(size(ratio)), log(ratio)];
    case 'pairs'
        required = {'dm_nm', 'temperature_k', 'pressure_pa'};
        if ~all(isfield(relation, required)) || ...
                ~isnumeric(relation.dm_nm) || ...
                numel(relation.dm_nm) ~= grid.Ne || ...
                any(~isfinite(relation.dm_nm(:))) || ...
                any(relation.dm_nm(:) <= 0)
            fail('Relation', 'Pairs need dm_nm per cell and the AAC state.');
        end
        coordinate = 'aerodynamic';
        dm_m = double(relation.dm_nm(:)) * 1e-9;
        rho = INV.RHO_EFF(d_m, dm_m, relation.temperature_k, ...
            relation.pressure_pa, cfg);
    otherwise
        fail('Relation', 'Use form power_law or pairs.');
end

% Applying k(dm) once, only to densities that do not yet carry it
[k, u_k, in_range, ~, k_provenance] = INV.CALIB_K(dm_m, cfg);
if ~relation.calibrated_1, rho = rho ./ k; end
particle_kg = pi / 6 * rho .* dm_m .^ 3;
cell_ugm3 = states .* particle_kg .* width * to_ugm3;
total = sum(cell_ugm3);

% Propagating each term linearly, k(dm) shared by every cell
u_number = NaN;
if isfield(options, 'covariance_cm6')
    covariance = options.covariance_cm6;
    if ~isnumeric(covariance) || ~isreal(covariance) || ...
            ~isequal(size(covariance), [grid.Ne grid.Ne]) || ...
            any(~isfinite(covariance(:)))
        fail('Covariance', 'Require an Ne x Ne state covariance (cm^-6).');
    end
    g = particle_kg .* width * to_ugm3;
    try
        [~, variance] = INV.DELTA_PROP(states, covariance, ...
            @(x, ~) deal(g.' * x, g.'), true(grid.Ne, 1));
    catch err
        if strcmp(err.identifier, 'sootMosaic:DELTA_PROP:Covariance')
            fail('Covariance', ...
                'The state covariance must be symmetric and nonnegative.');
        end
        rethrow(err);
    end
    u_number = sqrt(max(variance, 0)); % round-off only, after validation
end
u_relation = NaN;
if ~isempty(theta_jacobian) && isfield(relation, 'covariance') && ...
        ~isempty(relation.covariance)
    sigma = relation.covariance;
    if ~isnumeric(sigma) || ~isreal(sigma) || ...
            ~isequal(size(sigma), [2 2]) || any(~isfinite(sigma(:))) || ...
            norm(sigma - sigma.', 'fro') > 1e-10 * norm(sigma, 'fro') || ...
            min(eig((sigma + sigma.') / 2)) < -1e-10 * norm(sigma, 2)
        fail('Relation', ['The power-law covariance must be a real ' ...
            'symmetric positive semidefinite 2 x 2 matrix.']);
    end
    jacobian = cell_ugm3.' * theta_jacobian;
    u_relation = sqrt(max(jacobian * sigma * jacobian.', 0)); % round-off
end
u_calibration = abs(sum(cell_ugm3 .* u_k));
terms = [u_number, u_relation, u_calibration];
supplied = ~isnan(terms);
u_total = NaN;
if any(supplied), u_total = sqrt(sum(terms(supplied) .^ 2)); end
result = struct('mass_ugm3', total, 'coordinate', coordinate, ...
    'u_number_ugm3', u_number, 'u_relation_ugm3', u_relation, ...
    'u_calibration_ugm3', u_calibration, ...
    'u_total_ugm3', u_total, ...
    'terms_included', {{'number', 'relation', 'calibration'}}, ...
    'cell_mass_ugm3', cell_ugm3, 'particle_mass_kg', particle_kg, ...
    'rho_eff_kg_m3', rho, 'dm_nm', dm_m * 1e9, 'k', k, ...
    'k_u_rel', u_k, 'k_in_range', in_range, ...
    'mass_share_out_of_range', sum(cell_ugm3(~in_range)) / total, ...
    'calibrated_1', relation.calibrated_1, 'k_provenance', k_provenance);
result.terms_included = result.terms_included(supplied);
end

function yes = positive(value)
yes = isnumeric(value) && isscalar(value) && isreal(value) && ...
    isfinite(value) && value > 0;
end

function fail(reason, message)
error(['sootMosaic:MASS:' reason], '%s', message);
end
