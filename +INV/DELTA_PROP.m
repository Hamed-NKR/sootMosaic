function [value, covariance] = DELTA_PROP(x, state_covariance, ...
    statistic, window_1)
% "DELTA_PROP" propagates a covariance through a fixed-window statistic.
% ----------------------------------------------------------------------- %
%
% Inputs:
%     x: Nonnegative distribution (cm^-3)
%     state_covariance: Conditional Gaussian covariance (cm^-6)
%     statistic: Function returning [value, Jacobian] from (x, window_1)
%     window_1: Fixed logical reporting mask, passed unchanged (-)
% Outputs:
%     value: Statistic evaluated at x, in the statistic's physical unit
%     covariance: Jacobian * state_covariance * Jacobian', in squared units
% ----------------------------------------------------------------------- %
% Method: Sipkens et al. (2020, part II, Eq. 26) for state covariance;
%     ...first-order delta propagation, J Cov(x) J', with fixed windows.
% Reimplementation. Apply at each lambda and kernel draw before POST_MIX.
% Linear statistics are exact. Data-dependent window selection is excluded.

n = numel(x);
if ~isnumeric(x) || ~isreal(x) || size(x, 2) ~= 1 || isempty(x) || ...
        any(~isfinite(x) | x < 0) || ~isnumeric(state_covariance) || ...
        ~isreal(state_covariance) || ...
        ~isequal(size(state_covariance), [n, n]) || ...
        any(~isfinite(state_covariance(:))) || ...
        ~isa(statistic, 'function_handle') || ~islogical(window_1) || ...
        ~isvector(window_1) || numel(window_1) ~= n || ~any(window_1)
    error('sootMosaic:DELTA_PROP:Input', ...
        'Require a state, covariance and fixed mask.');
end
if norm(state_covariance-state_covariance', 'fro') > ...
        1e-10*norm(state_covariance, 'fro') || ...
        min(eig((state_covariance+state_covariance')/2)) < ...
        -1e-10*norm(state_covariance, 2)
    error('sootMosaic:DELTA_PROP:Covariance', ...
        'Require a symmetric nonnegative covariance.');
end
[value, j] = statistic(x, window_1(:));
if ~isnumeric(value) || ~isreal(value) || size(value, 2) ~= 1 || ...
        isempty(value) || any(~isfinite(value)) || ~isnumeric(j) || ...
        ~isreal(j) || ~isequal(size(j), [numel(value), n]) || ...
        any(~isfinite(j(:)))
    error('sootMosaic:DELTA_PROP:Statistic', ...
        'Require finite values and a Jacobian.');
end
covariance = j*state_covariance*j';
covariance = (covariance+covariance')/2;
end
