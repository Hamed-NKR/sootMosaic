function report = TEST_CONVERT_DPP()
% "TEST_CONVERT_DPP" checks the units of TRANSP.CONVERT_DPP against the...
%     ...typical soot values of Table 2 of Sipkens et al. (2023).
% ----------------------------------------------------------------------- %
%
% Inputs/output:
%     report: Structure array with fields name and pass, one entry per...
%         ...case. A failed case stops with the identifier...
%         ...sootMosaic:QA:ConvertDppFailed.
% ----------------------------------------------------------------------- %
%
% Table 2 states every quantity to three significant figures, so the...
%     ...densities and masses are compared within half a unit of the third...
%     ...figure. At dp = 17.8 nm the 'equations' method gives dm = 100 nm,...
%     ...a single particle mass of 0.267 fg (2.67e-19 kg) and an effective...
%     ...density of 510 kg/m3. The 'equations' and 'table' methods agree...
%     ...within 1.2 percent in dm and 0.5 percent in density at the Table 2...
%     ...primary particle diameters (largest differences 0.96 and 0.33...
%     ...percent, from the rounding of the tabulated diameters).
% ----------------------------------------------------------------------- %

names = {};
pass = [];

% Table 2 of Sipkens et al. (2023), typical soot in air
dm_tab = [20 30 50 75 100 200 300 500 750 1000]';                 % nm
m_tab = [0.00493 0.0135 0.0479 0.131 0.267 1.49 4.07 14.5 39.5 ...
    80.6]';                                                       % fg
rho_tab = [1180 954 731 592 510 356 288 221 179 154]';            % kg/m3
dp_tab = [10.1 11.7 14.0 16.1 17.8 22.7 26.1 31.3 36.0 39.8]';   % nm

% half a unit of the third significant figure of each tabulated value
half_unit = @(x) 0.5 * 10 .^ (floor(log10(x)) - 2);

% the row of Table 2 at dp = 17.8 nm
[rho, dm] = TRANSP.CONVERT_DPP(17.8, 'equations');
[names, pass] = add(names, pass, ...
    'dp = 17.8 nm gives dm = 100 nm', ...
    near(dm, 100, 1e-12));
[names, pass] = add(names, pass, ...
    'dp = 17.8 nm gives about 510 kg/m3 (Table 2 row, 509.93)', ...
    abs(rho - 510) <= half_unit(510) && abs(rho - 509.9324) < 1e-3);
m_fg = rho * pi * (dm * 1e-9) ^ 3 / 6 * 1e18;
[names, pass] = add(names, pass, ...
    'dp = 17.8 nm carries 0.267 fg, so 1 fg is 1e-18 kg', ...
    near(m_fg, 0.267, 1e-12));
[names, pass] = add(names, pass, ...
    'default method is equations', ...
    isequal(TRANSP.CONVERT_DPP(17.8), rho));

% every row of Table 2, primary diameter from the inverted TEM scaling
dp_eq = 17.8 * (dm_tab / 100) .^ 0.35;
[rho_eq, dm_eq] = TRANSP.CONVERT_DPP(dp_eq, 'equations');
[names, pass] = add(names, pass, ...
    'equations at the Table 2 dm return that dm', ...
    near(dm_eq, dm_tab, 1e-12));
[names, pass] = add(names, pass, ...
    'equations densities match Table 2 within rounding', ...
    all(abs(rho_eq - rho_tab) <= half_unit(rho_tab)));
m_eq = rho_eq .* pi .* (dm_eq * 1e-9) .^ 3 / 6 * 1e18;
[names, pass] = add(names, pass, ...
    'equations masses match Table 2 within rounding', ...
    all(abs(m_eq - m_tab) <= half_unit(m_tab)));

% equations against table at the Table 2 primary particle diameters
[rho_e, dm_e] = TRANSP.CONVERT_DPP(dp_tab, 'equations');
[rho_t, dm_t] = TRANSP.CONVERT_DPP(dp_tab, 'table');
[names, pass] = add(names, pass, ...
    'table method returns the Table 2 values', ...
    isequal(dm_t, dm_tab) && isequal(rho_t, rho_tab));
[names, pass] = add(names, pass, ...
    'equations and table agree within 1.2 percent in dm', ...
    all(abs(dm_e ./ dm_t - 1) <= 0.012));
[names, pass] = add(names, pass, ...
    'equations and table agree within 0.5 percent in density', ...
    all(abs(rho_e ./ rho_t - 1) <= 0.005));

% density in kg/m3
[names, pass] = add(names, pass, ...
    'densities lie between 100 and 2000 kg/m3 over the table range', ...
    all(rho_e > 100 & rho_e < 2000) && all(rho_t > 100 & rho_t < 2000));

% shape and options
[rho_r, dm_r] = TRANSP.CONVERT_DPP(dp_tab', 'equations');
[names, pass] = add(names, pass, ...
    'row input returns columns', ...
    iscolumn(rho_r) && iscolumn(dm_r) && isequal(rho_r, rho_e));
rho_p = TRANSP.CONVERT_DPP(17.8, 'equations', struct('m100_fg', 0.5));
[names, pass] = add(names, pass, ...
    'params override scales the density with the mass at 100 nm', ...
    near(rho_p, rho * 0.5 / 0.267, 1e-12));
[names, pass] = add(names, pass, ...
    'unknown method stops with sootMosaic:CONVERT_DPP:UnknownMethod', ...
    raises_error(@() TRANSP.CONVERT_DPP(17.8, 'fit'), ...
    'sootMosaic:CONVERT_DPP:UnknownMethod'));

report = struct('name', names, 'pass', num2cell(pass));
n_fail = sum(~pass);
for k = 1:numel(pass)
    fprintf('%s %s\n', ternary(pass(k), 'PASS', 'FAIL'), names{k})
end
fprintf('%d of %d cases pass.\n', sum(pass), numel(pass))
if n_fail > 0
    error('sootMosaic:QA:ConvertDppFailed', '%d of %d cases failed.', ...
        n_fail, numel(pass))
end

end

function [names, pass] = add(names, pass, name, ok)
names{end + 1, 1} = name;
pass(end + 1, 1) = logical(ok);
end

function ok = near(val, ref, tol)
ok = all(abs(val ./ ref - 1) <= tol);
end

function ok = raises_error(fn, id)
ok = false;
try
    fn();
catch err
    ok = strcmp(err.identifier, id);
end
end

function out = ternary(cond, a, b)
if cond, out = a; else, out = b; end
end
