function report = TEST_SLIP_CORRECTION(repoRoot)
% "TEST_SLIP_CORRECTION" checks the slip correction of TRANSP.CUNNINGHAM,...
%     ...its use in TRANSP.MOBIL, TRANSP.DIAMOBIL, TRANSP.AERODYN and...
%     ...UTILS.TABGEN, the slip option of the model profiles and the LD1...
%     ...and LD2 config loaders, and the slip model of LD2 resumes.
% ----------------------------------------------------------------------- %
%
% Inputs:
%     repoRoot: sootMosaic root folder (default the folder above +QA)
% ----------------------------------------------------------------------- %
%
% Outputs:
%     report: Structure array with fields name and pass, one entry per case
% ----------------------------------------------------------------------- %
%
% Hand calculated reference values are 2.9518077 for 1.257, 0.4 and 1.1...
%     ...at d = 100 nm and lambda = 68 nm (Kn = 1.36), 2.3432196 for the...
%     ...kim2005 constants at Kn = 1 and 2.3871484 for 1.254, 0.4 and 1.1...
%     ...at Kn = 1 (relative tolerance 1e-7), and the aerodynamic...
%     ...diameters of 1800 kg/m3 spheres under kim2005. The...
%     ...per_caller_7658971 model is compared with the expressions of...
%     ...commit 7658971 written out below and with caller outputs of...
%     ...commit 2b57f19 printed to 17 digits. A failed case stops with...
%     ...the identifier sootMosaic:QA:SlipCorrectionFailed.
% ----------------------------------------------------------------------- %

if nargin < 1 || isempty(repoRoot)
    repoRoot = fileparts(fileparts(mfilename('fullpath')));
end

names = {};
pass = [];
kim = 'kim2005';
old = 'per_caller_7658971';
rng_saved = rng;
restore_rng = onCleanup(@() rng(rng_saved));

% hand calculated values
lam = 67.3e-9;
[names, pass] = add(names, pass, ...
    'kim2005 at Kn = 1 is 2.3432196 (2.343)', ...
    near(TRANSP.CUNNINGHAM(2 * lam, lam, kim), 2.3432196278, 1e-7) && ...
    abs(TRANSP.CUNNINGHAM(2 * lam, lam, kim) - 2.343) < 5e-4);
cc_d = TRANSP.CUNNINGHAM(100e-9, 68e-9, old, 'TABGEN');
[names, pass] = add(names, pass, ...
    '1.257, 0.4, 1.1 form at 100 nm and 68 nm is 2.95181', ...
    near(cc_d, 2.9518076647, 1e-7) && abs(cc_d - 2.95181) < 5e-6);
[names, pass] = add(names, pass, ...
    'MOBIL constants of 7658971 at Kn = 1 are 2.3871484', ...
    near(TRANSP.CUNNINGHAM(2 * lam, lam, old, 'MOBIL'), 2.3871484335, 1e-7));

% per_caller_7658971 against the expressions of commit 7658971
d = 1e-9 * logspace(0, 4, 41)'; % 1 nm to 10 micrometer
lam_f = 4.98e-7;
kn = (2 * lam_f) ./ d;
cc_mobil = 1 + kn .* (1.254 + 0.4 .* exp(-1.1 ./ kn));
x = lam_f ./ (d / 2);
cc_dia1 = 1 + x .* (1.165 + 0.483 * exp(-0.997 ./ x));
x = 2 * lam_f ./ d;
cc_dia2 = 1 + x .* (1.165 + 0.483 * exp(-0.997 ./ x));
cc_aero = 1 + d .* (1.165 + 0.483 * exp(-0.997 ./ d));
dp = 1e9 * d;
cc_tab = 1 + (2 * 6.8e-8 ./ dp) .* (1.257 + 0.4 * exp(-0.55 * dp / 6.8e-8));
[names, pass] = add(names, pass, ...
    'per_caller_7658971 equals the 7658971 expressions bit for bit', ...
    isequal(TRANSP.CUNNINGHAM(d, lam_f, old, 'MOBIL'), cc_mobil) && ...
    isequal(TRANSP.CUNNINGHAM(d, lam_f, old, 'DIAMOBIL'), cc_dia1) && ...
    isequal(TRANSP.CUNNINGHAM(d, lam_f, old, 'DIAMOBIL'), cc_dia2) && ...
    isequal(TRANSP.CUNNINGHAM(d, [], old, 'AERODYN'), cc_aero) && ...
    isequal(TRANSP.CUNNINGHAM(dp, 6.8e-8, old, 'TABGEN'), cc_tab));
[names, pass] = add(names, pass, ...
    'AERODYN and TABGEN of 7658971 give cc close to 1', ...
    all(cc_aero(d <= 1e-6) - 1 < 2e-6) && all(cc_tab(dp >= 10) - 1 < 2e-8));

% one correction in every caller with kim2005
cc_k = TRANSP.CUNNINGHAM(d, lam_f, kim);
ok = isequal(cc_k, TRANSP.CUNNINGHAM(d, lam_f, kim, 'MOBIL')) && ...
    isequal(cc_k, TRANSP.CUNNINGHAM(d, lam_f, kim, 'DIAMOBIL')) && ...
    isequal(cc_k, TRANSP.CUNNINGHAM(d, lam_f, kim, 'AERODYN')) && ...
    isequal(cc_k, TRANSP.CUNNINGHAM(d, lam_f, kim, 'TABGEN')) && ...
    isequal(cc_k, TRANSP.CUNNINGHAM(d, lam_f, old, 'DIAMOBIL'));
[names, pass] = add(names, pass, ...
    'kim2005 is the same for every caller and equals DIAMOBIL of 7658971', ok);
kn = 2 * lam_f ./ d;
[names, pass] = add(names, pass, ...
    'kim2005 tends to 1 + 1.165 Kn and 1 + 1.648 Kn in the two limits', ...
    near((cc_k(end) - 1) / kn(end), 1.165, 1e-4) && ...
    near(cc_k(1) / kn(1), 1.165 + 0.483, 1e-3));

% invalid names
[names, pass] = add(names, pass, 'unknown slip model rejected', ...
    raises_error(@() TRANSP.CUNNINGHAM(d, lam_f, 'davies'), ...
    'sootMosaic:CUNNINGHAM:UnknownModel') && ...
    raises_error(@() TRANSP.CUNNINGHAM(d, lam_f, 1), ...
    'sootMosaic:CUNNINGHAM:UnknownModel'));
[names, pass] = add(names, pass, ...
    'per_caller_7658971 without a known caller rejected', ...
    raises_error(@() TRANSP.CUNNINGHAM(d, lam_f, old), ...
    'sootMosaic:CUNNINGHAM:UnknownCaller') && ...
    raises_error(@() TRANSP.CUNNINGHAM(d, lam_f, old, 'MARCH'), ...
    'sootMosaic:CUNNINGHAM:UnknownCaller'));

% Caller outputs of 2b57f19 printed to 17 digits, for three chains of...
%     ...30 nm primaries (monomer, dimer, five-chain), the room preset...
%     ...(293.15 K, 1.813e-5 Pa.s, 68 nm) and the flame preset (1700 K,...
%     ...5.647e-5 Pa.s, 498 nm). MOBIL continuum with c_dt 1e-3 and the...
%     ...constants of params_const below, DIAMOBIL with da = 30, 41 and...
%     ...74 nm, AERODYN with that dm and 1800 kg/m3, TABGEN after rng(7).
%     ...The relative tolerance of 1e-15 is about four units in the last...
%     ...place.
hist = historical();
pars = aggregates(30e-9, [1; 2; 5]);
params_const = table([1800; 0.02897; 1.380649e-23], ...
    'VariableNames', {'Value'});
room = struct('temp', 293.15, 'mu', 1.813e-5, 'lambda', 6.8e-8);
flame = struct('temp', 1700, 'mu', 5.647e-5, 'lambda', 4.98e-7);
fls = {room, flame};
da_h = [30e-9; 41e-9; 74e-9];
ok_m = isequal(pars.dg, hist.dg);
ok_d = true;
ok_a = true;
for j = 1 : 2
    p = quiet(@() TRANSP.MOBIL(pars, fls{j}, params_const, ...
        struct('mtd', 'continuum', 'c_dt', 1e-3)));
    ok_m = ok_m && near(p.f, hist.f_mobil{j}, 1e-15) && ...
        near(p.tau, hist.tau_mobil{j}, 1e-15);
    dm = TRANSP.DIAMOBIL(pars.dg, da_h, fls{j});
    ok_d = ok_d && near(dm, hist.dm_dia{j}, 1e-15) && ...
        near(TRANSP.DIAMOBIL(pars.dg, da_h, fls{j}, old), hist.dm_dia{j}, 1e-15);
    ok_a = ok_a && near(TRANSP.AERODYN(pars.pp, dm, 1800), ...
        hist.dae_aero{j}, 1e-15);
end
[names, pass] = add(names, pass, ...
    'MOBIL without the option gives the friction and tau of 2b57f19', ok_m);
[names, pass] = add(names, pass, ...
    'DIAMOBIL by default and with per_caller_7658971 gives dm of 2b57f19', ok_d);
[names, pass] = add(names, pass, ...
    'AERODYN without the option gives dae of 2b57f19', ok_a);
tab_0 = TABGEN_quiet([20; 25; 30], [100; 200; 300], []);
tab_1 = TABGEN_quiet([20; 25; 30], [100; 200; 300], old);
[names, pass] = add(names, pass, ...
    'TABGEN without the option gives x and dae of 2b57f19', ...
    near(tab_0.x, hist.x_tab, 1e-15) && near(tab_0.dae, hist.dae_tab, 1e-15) ...
    && isequal(tab_1.x, tab_0.x) && isequal(tab_1.dae, tab_0.dae));
[names, pass] = add(names, pass, ...
    'TABGEN stops with any other slip model', ...
    raises_error(@() UTILS.TABGEN(20, 100, kim), ...
    'sootMosaic:TABGEN:ModelUnavailable') && ...
    raises_error(@() UTILS.TABGEN(20, 100, 'davies'), ...
    'sootMosaic:TABGEN:ModelUnavailable'));

% Kim correction written out here, independent of TRANSP.CUNNINGHAM
cc_kim = @(kn) 1 + kn .* (1.165 + 0.483 * exp(-0.997 ./ kn));

% MOBIL, continuum method
fl = struct('temp', 298, 'p', 101325, 'mu', 1.836437388e-5, ...
    'lambda', 67.834769e-9);
mu = fl.mu;
opts = struct('mtd', 'continuum', 'c_dt', 1e-3, 'slip', kim);
[p1, o1] = quiet(@() TRANSP.MOBIL(pars, fl, params_const, opts));
[names, pass] = add(names, pass, ...
    'MOBIL with kim2005 uses the Kim correction', ...
    strcmp(o1.slip, kim) && isequal(p1.f, (3 * pi * mu) .* p1.dm ./ ...
    cc_kim((2 * fl.lambda) ./ p1.dm)) && ...
    isequal(p1.kn_kin, (2 * fl.lambda) ./ p1.dm));
[~, o0] = quiet(@() TRANSP.MOBIL(pars, fl, params_const, ...
    rmfield(opts, 'slip')));
[names, pass] = add(names, pass, ...
    'MOBIL without the option records per_caller_7658971', ...
    strcmp(o0.slip, old));

% MOBIL interp against the adjusted sphere friction of DIAMOBIL at the...
%     ...room and flame presets and at 298 K. DIAMOBIL solves g(x) = f(x)...
%     ...- f_not = 0 with f(x) = 3 pi mu x / Cc(2 lambda / x) and f_not...
%     ...its adjusted sphere friction. fzero (R2025b, lines 478 to 480)...
%     ...stops when |c - b| / 2 <= 2 TolX max(|b|, 1) = 2 eps x0 (x0 the...
%     ...initial guess, below 1 m), so the bracket [b, c] can span 4 eps...
%     ...x0, and returns the endpoint b with the smaller computed residual,...
%     ...g(b) and g(c) of opposite signs. Hence |g(b)| <= |g(b) - g(c)| /...
%     ...2 plus the evaluation error of f. f has a logarithmic slope...
%     ...between 1 and 2, so |f(b) - f(c)| <= 2 f |c - b| / dm <= 8 eps x0...
%     ...f / dm, and the root term is 4 eps x0 / dm. MOBIL computes f with...
%     ...the same operations as g, so it adds no rounding. The rounding...
%     ...allowance is 10 eps, the sum of 4.6 eps for evaluating f (four...
%     ...products and quotients and 5.2 units of 2^-53 in Cc), 4 eps for...
%     ...the two product orders of f_adj here and f_not in DIAMOBIL (Cc is...
%     ...the same in both), 0.5 eps for the ratio below, rounded up.
fls = {room, flame, fl};
ok = true;
dev_kim = 0;
dev_eps = 0;
for j = 1 : 3
    rng(3);
    opts = struct('mtd', 'interp', 'c_dt', 1e-3, 'slip', kim);
    p2 = quiet(@() TRANSP.MOBIL(pars, fls{j}, params_const, opts));
    dm_c = 0.75 * p2.dg;
    r_adj = p2.da.^2 ./ (2 * dm_c);
    f_adj = 3 * pi * fls{j}.mu * dm_c ./ cc_kim(fls{j}.lambda ./ r_adj);
    x0 = (dm_c + p2.da) / 2;
    bound = 4 * eps * x0 ./ p2.dm + 10 * eps;
    dev = abs(p2.f ./ f_adj - 1);
    ok = ok && all(dev <= bound);
    dev_kim = max([dev_kim; dev ./ bound]);
    dev_eps = max([dev_eps; dev / eps]);
end
[names, pass] = add(names, pass, ...
    'MOBIL friction equals the adjusted sphere friction within the bound', ok);
rng(3);
opts.slip = old;
p3 = quiet(@() TRANSP.MOBIL(pars, fl, params_const, opts));
dev_old = max(abs(p3.f ./ f_adj - 1));
[names, pass] = add(names, pass, ...
    'the 7658971 constants of MOBIL differ from the adjusted sphere', ...
    isequal(p3.da, p2.da) && near(p3.dm, p2.dm, 1e-8) && dev_old > 1e-3);
fprintf(['MOBIL interp friction against the adjusted sphere, kim2005 at ', ...
    '%.3g of the bound (largest difference %.3g eps), ', ...
    'per_caller_7658971 %.3g\n'], dev_kim, dev_eps, dev_old);
[names, pass] = add(names, pass, ...
    'DIAMOBIL with kim2005 is within 1e-8 of the 7658971 diameter', ...
    near(TRANSP.DIAMOBIL(p2.dg, p2.da, fl), p2.dm, 1e-8));

% AERODYN with kim2005 and the reference density of 1000 kg/m3. Spheres...
%     ...at dm = d solve dae^2 Cc(dae) = 1.8 d^2 Cc(d), values from a...
%     ...separate bisection (notes of patch 16).
lam_f = 497.999444e-9;
sph = {[1, 30e-9, 0, 0, 0]};
big = {[1, 100e-9, 0, 0, 0]};
[names, pass] = add(names, pass, ...
    'AERODYN with kim2005 gives the hand values for 1800 kg/m3 spheres', ...
    near(TRANSP.AERODYN(sph, 30e-9, 1800, fl, kim), 51.118675846e-9, 1e-9) ...
    && near(TRANSP.AERODYN(big, 100e-9, 1800, fl, kim), 155.711600894e-9, ...
    1e-9) && near(TRANSP.AERODYN(sph, 30e-9, 1800, ...
    struct('lambda', lam_f), kim), 53.589466908e-9, 1e-9));
dae = TRANSP.AERODYN(pars.pp, p2.dm, 1800, fl, kim);
m = 1800 * (pi / 6) * cellfun(@(q) sum(q(:, 2).^3), pars.pp);
res = dae - sqrt((6 / (pi * 1000)) * (m ./ p2.dm) .* ...
    (cc_kim(2 * fl.lambda ./ p2.dm) ./ cc_kim(2 * fl.lambda ./ dae)));
[names, pass] = add(names, pass, ...
    'AERODYN with kim2005 solves the aerodynamic equation for aggregates', ...
    max(abs(res ./ dae)) < 1e-12);
[names, pass] = add(names, pass, ...
    'AERODYN without the option keeps dae = d for a sphere at dm = d', ...
    near(TRANSP.AERODYN(sph, 30e-9, 1800), 30e-9, 1e-12));
[names, pass] = add(names, pass, ...
    'AERODYN with kim2005 needs the mean free path', ...
    raises_error(@() TRANSP.AERODYN(pars.pp, p2.dm, 1800, [], kim), ...
    'sootMosaic:AERODYN:MissingMeanFreePath'));

% model profiles and loaders
m1 = UTILS.MODEL_PROFILE('article1_7658971', 'LD1');
m2 = UTILS.MODEL_PROFILE('article1_7658971', 'LD2');
m3 = UTILS.MODEL_PROFILE('current', 'LD1');
[m4, known] = UTILS.MODEL_PROFILE('current', 'LD2');
[names, pass] = add(names, pass, 'profile slip defaults', ...
    strcmp(m1.slip_correction, old) && strcmp(m2.slip_correction, old) && ...
    strcmp(m3.slip_correction, kim) && strcmp(m4.slip_correction, kim) && ...
    isequal(known.slip_correction, {kim, old}));

tmp = tempname;
mkdir(tmp);
cleanup = onCleanup(@() rmdir(tmp, 's'));
ld1 = jsondecode(fileread(fullfile(repoRoot, 'config', 'main_ld1', ...
    'main_ld1_config.example.json')));
ld2 = jsondecode(fileread(fullfile(repoRoot, 'config', 'main_ld2', ...
    'main_ld2_from_main_scatter_config.example.json')));
f1 = @(c) UTILS.LOAD_MAIN_LD1_CONFIG(write_config(tmp, c));
f2 = @(c) UTILS.LOAD_MAIN_LD2_CONFIG(write_config(tmp, c));
cfg1 = f1(ld1);
cfg2 = f2(ld2);
[names, pass] = add(names, pass, 'example configs use kim2005', ...
    strcmp(cfg1.model.slip_correction, kim) && ...
    strcmp(cfg1.transport.mobility_options.slip, kim) && ...
    strcmp(cfg2.model.slip_correction, kim) && ...
    strcmp(cfg2.transport.mobility_options.slip, kim));
c1 = ld1;
c1.transport.mobility_options = rmfield(c1.transport.mobility_options, 'slip');
c2 = ld2;
c2.transport.mobility_options = rmfield(c2.transport.mobility_options, 'slip');
cfg1 = f1(c1);
cfg2 = f2(c2);
[names, pass] = add(names, pass, ...
    'the current profile gives kim2005 when slip is absent', ...
    strcmp(cfg1.transport.mobility_options.slip, kim) && ...
    strcmp(cfg2.transport.mobility_options.slip, kim));
c1 = rmfield(c1, 'model_profile');
c2 = rmfield(c2, 'model_profile');
c2.transport.fluid = rmfield(c2.transport.fluid, 'pressure');
cfg1 = quiet(@() f1(c1));
cfg2 = quiet(@() f2(c2));
[names, pass] = add(names, pass, ...
    'configs without profile run per_caller_7658971', ...
    strcmp(cfg1.model.slip_correction, old) && ...
    strcmp(cfg1.transport.mobility_options.slip, old) && ...
    strcmp(cfg2.model.slip_correction, old) && ...
    strcmp(cfg2.transport.mobility_options.slip, old));
c1 = ld1;
c1.transport.mobility_options.slip = old;
cfg1 = f1(c1);
[names, pass] = add(names, pass, ...
    'a configured slip model overrides the profile and is saved', ...
    strcmp(cfg1.model.profile, 'current') && ...
    strcmp(cfg1.model.slip_correction, old) && ...
    strcmp(cfg1.transport.mobility_options.slip, old));
c1.transport.mobility_options.slip = 'davies';
c2 = ld2;
c2.transport.mobility_options.slip = 'davies';
[names, pass] = add(names, pass, 'loaders reject unknown slip models', ...
    raises_error(@() f1(c1), ...
    'sootMosaic:LOAD_MAIN_LD1_CONFIG:InvalidChoice') && ...
    raises_error(@() f2(c2), 'sootMosaic:LOAD_MAIN_LD2_CONFIG:InvalidChoice'));

% explicit fields of the example configs win over the profile
ld2s = jsondecode(fileread(fullfile(repoRoot, 'config', 'main_ld2', ...
    'main_ld2_from_main_scale_config.example.json')));
examples = {ld1, ld2, ld2s};
loaders = {f1, f2, f2};
presets = {'flame', 'room', 'room'};
ok_keep = true;
ok_drop = true;
for i = 1 : 3
    c = examples{i};
    c.model_profile = 'article1_7658971';
    cfg = quiet(@() loaders{i}(c));
    ok_keep = ok_keep && strcmp(cfg.model.profile, 'article1_7658971') && ...
        strcmp(cfg.model.slip_correction, kim) && ...
        strcmp(cfg.model.fluid_properties, 'sutherland');
    c.transport.mobility_options = rmfield(c.transport.mobility_options, ...
        'slip');
    c.transport.fluid_options = rmfield(c.transport.fluid_options, 'amb');
    cfg = quiet(@() loaders{i}(c));
    ok_drop = ok_drop && strcmp(cfg.model.slip_correction, old) && ...
        strcmp(cfg.transport.mobility_options.slip, old) && ...
        strcmp(cfg.model.fluid_properties, presets{i});
end
[names, pass] = add(names, pass, ...
    'article1_7658971 keeps the explicit slip and amb of the examples', ...
    ok_keep);
[names, pass] = add(names, pass, ...
    'article1_7658971 without explicit slip and amb gives the 7658971 models', ...
    ok_drop);

% resume of LD2 checkpoints that advance two transport steps
cc_mobil = @(kn) 1 + kn .* (1.254 + 0.4 .* exp(-1.1 ./ kn));
model_p15 = struct('profile', 'current', 'fluid_properties', 'sutherland');
mob = struct('mtd', 'continuum', 'c_dt', 1);
[ok, out] = resume_checkpoint(fullfile(tmp, 'r1'), model_p15, mob, true);
[names, pass] = add(names, pass, ...
    'resume without a slip model advances with per_caller_7658971', ...
    ok && strcmp(out.cfg_ld2.model.slip_correction, old) && ...
    strcmp(out.opts_mobil.slip, old) && ...
    strcmp(out.cfg_ld2.model.fluid_properties, 'sutherland') && ...
    advanced(out) && near(out.pars_LD2.f, friction(out, cc_mobil), 1e-15));
model_p16 = UTILS.MODEL_PROFILE('current', 'LD2');
mob.slip = kim;
[ok, out] = resume_checkpoint(fullfile(tmp, 'r2'), model_p16, mob, false);
[names, pass] = add(names, pass, ...
    'resume keeps a saved slip model and advances with kim2005', ...
    ok && isequal(out.cfg_ld2.model, model_p16) && ...
    strcmp(out.opts_mobil.slip, kim) && advanced(out) && ...
    near(out.pars_LD2.f, friction(out, cc_kim), 1e-15));
[ok, out] = resume_checkpoint(fullfile(tmp, 'r3'), [], ...
    struct('mtd', 'continuum', 'c_dt', 1), false);
model_r3 = UTILS.MODEL_PROFILE('article1_7658971', 'LD2');
model_r3.fluid_properties = 'sutherland'; % ambient name of the checkpoint
model_r3.mobility = 'sorensen_eq17'; % method of the checkpoint options
[names, pass] = add(names, pass, ...
    'resume without model options advances with per_caller_7658971', ...
    ok && isequal(out.cfg_ld2.model, model_r3) && ...
    strcmp(out.opts_mobil.slip, old) && advanced(out) && ...
    near(out.pars_LD2.f, friction(out, cc_mobil), 1e-15));

clear cleanup restore_rng
report = struct('name', names, 'pass', num2cell(pass));
for i = 1 : numel(pass)
    if pass(i)
        fprintf('PASS %s\n', names{i});
    else
        fprintf('FAIL %s\n', names{i});
    end
end
if ~all(pass)
    error('sootMosaic:QA:SlipCorrectionFailed', '%d of %d cases failed.', ...
        sum(~pass), numel(pass))
end

end

function [names, pass] = add(names, pass, name, ok)
names{end + 1, 1} = name;
pass(end + 1, 1) = logical(ok);
end

function ok = near(val, ref, tol)
ok = all(abs(val ./ ref - 1) <= tol);
end

function pars = aggregates(dpp, npp)
% Straight chains of touching primaries along x, one aggregate per entry...
%     ...(columns index, diameter, x, y, z and subaggregate label)
n_agg = numel(npp);
pp = cell(n_agg, 1);
dg = zeros(n_agg, 1);
for i = 1 : n_agg
    xc = dpp * ((1 : npp(i))' - (npp(i) + 1) / 2);
    pp{i} = [sum(npp(1 : i - 1)) + (1 : npp(i))', dpp * ones(npp(i), 1), ...
        xc, zeros(npp(i), 2), i * ones(npp(i), 1)];
    dg(i) = 2 * sqrt(mean(xc.^2) + 0.15 * dpp^2); % 3/5 of radius squared
end
pars = struct('n', npp, 'pp', {pp}, 'dg', dg);
end

function tab = TABGEN_quiet(dpp, dm, slip)
% Seeding the initial guess of the aerodynamic diameter iteration
rng(7);
if isempty(slip)
    tab = UTILS.TABGEN(dpp, dm);
else
    tab = UTILS.TABGEN(dpp, dm, slip);
end
end

function varargout = quiet(fun) %#ok<INUSD> called in evalc
% Running fun with its printed output and warnings captured
varargout = cell(1, max(nargout, 1));
[~, varargout{:}] = evalc('fun()');
end

function ok = raises_error(fun, id) %#ok<INUSL> called in evalc
ok = false;
try
    evalc('fun();');
catch err
    ok = strcmp(err.identifier, id);
end
end

function ok = raises_warning(fun, id)
% Turning the warning into an error to read its identifier
state = warning('error', id);
restore = onCleanup(@() warning(state));
ok = raises_error(fun, id);
end

function ok = no_warning(fun, ids) %#ok<INUSL> called in evalc
state = warning;
restore = onCleanup(@() warning(state));
for i = 1 : numel(ids)
    warning('error', ids{i});
end
ok = true;
try
    evalc('fun();');
catch
    ok = false;
end
end

