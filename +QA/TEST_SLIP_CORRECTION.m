function ok = advanced(out)
% Two transport steps after the checkpoint at k = 1
ok = numel(out.ensdata.t) == 3 && all(diff(out.ensdata.t) > 0) && ...
    out.k == 4;
end

function f = friction(out, cc)
% Friction from the saved mobility diameter and a given correction
dm = out.pars_LD2.dm;
f = (3 * pi * out.fl.mu) .* dm ./ cc((2 * out.fl.lambda) ./ dm);
end

