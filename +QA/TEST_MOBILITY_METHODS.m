function report = TEST_MOBILITY_METHODS(repoRoot)
% "TEST_MOBILITY_METHODS" checks the mobility methods of TRANSP.MOBIL,...
%     ...the continuum diameters of TRANSP.CONTINUUM_DM, the continuum...
%     ...diameter and root solve options of TRANSP.DIAMOBIL, their model...
%     ...profile options, the LD1 and LD2 config loaders and LD2 resumes.
% ----------------------------------------------------------------------- %
%
% Inputs:
%     repoRoot: sootMosaic root folder (default the folder above +QA)
% ----------------------------------------------------------------------- %
%
% Outputs:
%     report: Structure array with fields name and pass, one entry per case
% ----------------------------------------------------------------------- %
%
% Reference values are written out below from reference 8 of the README,...
%     ...beta = 1.29 N^-0.13 (Eq. 17) at N = 3, 10, 50 and 74, Rm / a =...
%     ...N^0.46 (Eq. 18a) at N = 2 and 0.65 N^0.56 (Eq. 18b), and the...
%     ...doublet ratio 2^0.46 / sqrt(1.6), all evaluated independently of...
%     ...the tested implementation to ten digits. A failed case stops with...
%     ...the identifier...
%     ...sootMosaic:QA:MobilityMethodsFailed.
% ----------------------------------------------------------------------- %

if nargin < 1 || isempty(repoRoot)
    repoRoot = fileparts(fileparts(mfilename('fullpath')));
end

names = {};
pass = [];
kim = 'kim2005';
rng_saved = rng;
restore_rng = onCleanup(@() rng(rng_saved));

% Eq. 17, 18a and 18b literals (relative tolerance 1e-9)
n_17 = [3; 10; 50; 74];
beta_17 = [1.1183144774; 0.9562902113; 0.7757532607; 0.7372072316];
[names, pass] = add(names, pass, ...
    'eq17 gives beta = 1.29 N^-0.13 at N = 3, 10, 50 and 74', ...
    near(TRANSP.CONTINUUM_DM(n_17, ones(4, 1), [], 'eq17'), beta_17, 1e-9));
[names, pass] = add(names, pass, ...
    'backbone uses Eq. 17 for N from 3 to 74', ...
    near(TRANSP.CONTINUUM_DM(n_17, ones(4, 1), nan(4, 1), 'backbone'), ...
    beta_17, 1e-9));
n_l = [75; 100; 1000];
[names, pass] = add(names, pass, ...
    'backbone gives 0.75 dg above N = 74 (Eq. 18b for Df 1.78, kf 1.3)', ...
    isequal(TRANSP.CONTINUUM_DM(n_l, [2; 3; 4], nan(3, 1), 'backbone'), ...
    0.75 * [2; 3; 4]));
[names, pass] = add(names, pass, ...
    'backbone doublet ratio is 2^0.46 / sqrt(1.6) = 1.0874612905', ...
    near(TRANSP.CONTINUUM_DM(2, 1, nan, 'backbone'), 1.0874612905, 1e-9));
% Eqs. 18a and 18b meet at N = (1 / 0.65)^10 = 74.28, so N = 74 is the...
%     ...last small-N value (7.2418010761 against 7.2390757261 at 74,...
%     ...and 18b above 18a at 75)
[names, pass] = add(names, pass, ...
    'Eqs. 18a and 18b cross between N = 74 and 75', ...
    74^0.46 > 0.65 * 74^0.56 && 75^0.46 < 0.65 * 75^0.56 && ...
    near(74^0.46, 7.2418010761, 1e-9) && ...
    near(0.65 * 74^0.56, 7.2390757261, 1e-9));
pars = PAR.SIZING(aggregates(30e-9, [1; 2; 3; 74; 75]));
dm_b = TRANSP.CONTINUUM_DM(pars.n, pars.dg, [30e-9; nan(4, 1)], 'backbone');
[names, pass] = add(names, pass, ...
    'backbone gives dp for a monomer and 2^0.46 dp (Eq. 18a) for a doublet', ...
    dm_b(1) == 30e-9 && near(dm_b(2), 1.3755418181 * 30e-9, 1e-9));
npp = (1 : 2000)';
dg = 1e-9 * (1 + rand(2000, 1)) .* npp.^0.56;
[names, pass] = add(names, pass, ...
    'eq17 equals the expression of 7658971 bit for bit', ...
    isequal(TRANSP.CONTINUUM_DM(npp, dg, [], 'eq17'), ...
    1.29 * npp.^(-0.13) .* dg));
[names, pass] = add(names, pass, 'unknown continuum variant rejected', ...
    raises_error(@() TRANSP.CONTINUUM_DM(1, 1, 1, 'eq18'), ...
    'sootMosaic:CONTINUUM_DM:UnknownVariant'));

% MOBIL methods on chains of 30 nm primaries
params_const = table([1800; 0.02897; 1.380649e-23], ...
    'VariableNames', {'Value'});
room = struct('temp', 293.15, 'mu', 1.813e-5, 'lambda', 6.8e-8);
flame = struct('temp', 1700, 'mu', 5.647e-5, 'lambda', 4.98e-7);
p_c = quiet(@() TRANSP.MOBIL(pars, flame, params_const, ...
    struct('mtd', 'continuum', 'c_dt', 1e-3)));
p_s = quiet(@() TRANSP.MOBIL(pars, flame, params_const, ...
    struct('mtd', 'sorensen_eq17', 'c_dt', 1e-3)));
[names, pass] = add(names, pass, ...
    'continuum is the earlier name of sorensen_eq17', ...
    isequaln(p_c, p_s) && isequal(p_c.dm, 1.29 * pars.n.^(-0.13) .* pars.dg));
p_b = quiet(@() TRANSP.MOBIL(pars, flame, params_const, ...
    struct('mtd', 'sorensen_backbone', 'c_dt', 1e-3)));
[names, pass] = add(names, pass, ...
    'MOBIL sorensen_backbone gives the backbone diameters', ...
    isequal(p_b.dm, dm_b));
rng(5);
p_i = quiet(@() TRANSP.MOBIL(pars, flame, params_const, ...
    struct('mtd', 'interp', 'c_dt', 1e-3)));
rng(5);
p_f = quiet(@() TRANSP.MOBIL(pars, flame, params_const, ...
    struct('mtd', 'free_molecular', 'c_dt', 1e-3)));
[names, pass] = add(names, pass, ...
    'MOBIL free_molecular sets dm to the projected area diameter', ...
    isequal(p_f.dm, p_f.da) && isequal(p_f.da, p_i.da));
[names, pass] = add(names, pass, 'unknown mobility method rejected', ...
    raises_error(@() TRANSP.MOBIL(pars, flame, params_const, ...
    struct('mtd', 'kinetic')), 'sootMosaic:MOBIL:UnknownMethod'));

% sphere identity of the backbone interpolation at every Kn
cur = struct('mtd', 'interp', 'c_dt', 1e-3, 'slip', kim, ...
    'continuum_diameter', 'sorensen_backbone', 'root_solve', 'bracketed');
spheres = PAR.SIZING(aggregates(30e-9, [1; 1; 1]));
lam = 30e-9 * logspace(-4, 4, 17);
ok = true;
for j = 1 : numel(lam)
    fl_j = struct('temp', 298, 'mu', 1.84e-5, 'lambda', lam(j));
    p = quiet(@() TRANSP.MOBIL(spheres, fl_j, params_const, cur));
    ok = ok && isequal(p.dm, 30e-9 * ones(3, 1)) && ...
        near(p.f, 3 * pi * fl_j.mu * 30e-9 ./ ...
        TRANSP.CUNNINGHAM(30e-9, lam(j), kim), 1e-15);
    dm_d = TRANSP.DIAMOBIL(spheres.dg, 30e-9 * ones(3, 1), fl_j, kim, ...
        struct('continuum', 'sorensen_backbone', 'root', 'bracketed', ...
        'npp', ones(3, 1), 'dpp1', 30e-9 * ones(3, 1)));
    ok = ok && isequal(dm_d, 30e-9 * ones(3, 1));
end
[names, pass] = add(names, pass, ...
    'backbone interp gives dm = dp for a sphere at Kn from 2e-4 to 2e4', ok);

% interpolation of a sphere with 0.75 dg, the article 1 setting (0.5809 dp
%     ...in the continuum)
dm_l = zeros(numel(lam), 1);
for j = 1 : numel(lam)
    fl_j = struct('temp', 298, 'mu', 1.84e-5, 'lambda', lam(j));
    dm_l(j) = TRANSP.DIAMOBIL(spheres.dg(1), 30e-9, fl_j);
end
[names, pass] = add(names, pass, ...
    'fixed_075dg interp of a sphere goes from 0.75 sqrt(0.6) dp to dp', ...
    all(dm_l < 30e-9) && all(diff(dm_l) > 0) && ...
    near(dm_l(1), 0.75 * sqrt(0.6) * 30e-9, 1e-3) && ...
    near(dm_l(end), 30e-9, 1e-3) && dm_l(9) < 0.95 * 30e-9);
fprintf('fixed_075dg interp of a 30 nm sphere at lambda = dp, dm = %.4f dp\n', ...
    dm_l(9) / 30e-9);

% interp limits with the backbone continuum diameter, bracketed solve
ratios = [0.5, 0.9, 1.1, 2, 4];
n_c = [2, 5, 20, 200];
lam_r = logspace(-5, 5, 11); % lambda / dm_c
ok_lim = true;
ok_mono = true;
ok_brk = true;
err_fm = 0;
err_c = 0;
for n = n_c
    dg_n = 30e-9 * sqrt(0.6 + n^1.12 / 1.3); % a gyration diameter
    dm_c = TRANSP.CONTINUUM_DM(n, dg_n, nan, 'backbone');
    for r = ratios
        e_fm = zeros(1, numel(lam_r));
        e_c = zeros(1, numel(lam_r));
        for j = 1 : numel(lam_r)
            fl_j = struct('temp', 298, 'mu', 1.84e-5, 'lambda', ...
                lam_r(j) * dm_c);
            dm = TRANSP.DIAMOBIL(dg_n, r * dm_c, fl_j, kim, ...
                struct('continuum', 'sorensen_backbone', 'root', ...
                'bracketed', 'npp', n, 'dpp1', nan));
            e_fm(j) = abs(dm / (r * dm_c) - 1);
            e_c(j) = abs(dm / dm_c - 1);
            ok_brk = ok_brk && dm >= min(1, r) * dm_c && ...
                dm <= max(1, r) * dm_c;
        end
        ok_lim = ok_lim && e_fm(end) < 1e-3 && e_c(1) < 1e-3;
        ok_mono = ok_mono && all(diff(e_fm) < 0) && all(diff(e_c) > 0);
        err_fm = max(err_fm, e_fm(end));
        err_c = max(err_c, e_c(1));
    end
end
[names, pass] = add(names, pass, ...
    'interp tends to da as Kn grows and to beta dg as Kn falls', ...
    ok_lim && ok_mono);
[names, pass] = add(names, pass, ...
    'interp root lies between the continuum diameter and da', ok_brk);
fprintf(['interp limits, largest |dm/da - 1| at lambda = 1e5 dm_c %.2g, ', ...
    'largest |dm/dm_c - 1| at lambda = 1e-5 dm_c %.2g\n'], err_fm, err_c);

% bracketed and start point solves, friction against the adjusted sphere
cc_kim = @(kn) 1 + kn .* (1.165 + 0.483 .* exp(-0.997 ./ kn));
p2 = PAR.SIZING(aggregates(30e-9, [1; 2; 5; 20; 74; 75; 150]));
fl_298 = struct('temp', 298, 'mu', 1.8369e-5, 'lambda', 6.7835e-8);
fls = {room, flame, fl_298};
ok = true;
ok_same = true;
cur_s = cur;
cur_s.root_solve = 'start_point_7658971';
dev_max = 0;
for j = 1 : 3
    rng(3);
    pc = quiet(@() TRANSP.MOBIL(p2, fls{j}, params_const, cur));
    dm_c = TRANSP.CONTINUUM_DM(p2.n, p2.dg, [30e-9; nan(6, 1)], 'backbone');
    r_adj = pc.da.^2 ./ (2 * dm_c);
    f_adj = 3 * pi * fls{j}.mu * dm_c ./ cc_kim(fls{j}.lambda ./ r_adj);
    x0 = (dm_c + pc.da) / 2;
    bound = 4 * eps * x0 ./ pc.dm + 10 * eps;
    dev = abs(pc.f ./ f_adj - 1);
    ok = ok && all(dev(2 : end) <= bound(2 : end)) && pc.dm(1) == 30e-9;
    dev_max = max([dev_max; dev(2 : end) ./ bound(2 : end)]);
    rng(3);
    ps = quiet(@() TRANSP.MOBIL(p2, fls{j}, params_const, cur_s));
    ok_same = ok_same && isequal(ps.da, pc.da) && near(ps.dm, pc.dm, 1e-12);
end
[names, pass] = add(names, pass, ...
    'bracketed friction equals the adjusted sphere friction in the bound', ...
    ok);
[names, pass] = add(names, pass, ...
    'bracketed and start point solves agree to 1e-12', ok_same);
fprintf('bracketed friction, largest deviation %.2g of the bound\n', dev_max);
% rows and columns give the same diameters
dg_c = p2.dg(:);
da_c = 1.3 * dg_c;
n_c2 = p2.n(:);
d1_c = [30e-9; nan(6, 1)];
o_col = struct('continuum', 'sorensen_backbone', 'root', 'bracketed', ...
    'npp', n_c2, 'dpp1', d1_c);
o_row = struct('continuum', 'sorensen_backbone', 'root', 'bracketed', ...
    'npp', n_c2', 'dpp1', d1_c');
ref_b = TRANSP.DIAMOBIL(dg_c, da_c, fl_298, kim, o_col);
ref_l = TRANSP.DIAMOBIL(dg_c, da_c, fl_298);
ok_rc = true;
for in = {{dg_c', da_c}, {dg_c, da_c'}, {dg_c', da_c'}}
    ok_rc = ok_rc && ...
        isequal(TRANSP.DIAMOBIL(in{1}{1}, in{1}{2}, fl_298, kim, o_col), ref_b) ...
        && isequal(TRANSP.DIAMOBIL(in{1}{1}, in{1}{2}, fl_298, kim, o_row), ...
        ref_b) && isequal(TRANSP.DIAMOBIL(in{1}{1}, in{1}{2}, fl_298), ref_l);
end
ok_rc = ok_rc && isequal(TRANSP.CONTINUUM_DM(n_c2', dg_c, d1_c', ...
    'backbone'), TRANSP.CONTINUUM_DM(n_c2, dg_c, d1_c, 'backbone')) && ...
    isequal(TRANSP.CONTINUUM_DM(n_c2', dg_c, [], 'eq17'), ...
    TRANSP.CONTINUUM_DM(n_c2, dg_c, [], 'eq17')) && ...
    raises_error(@() TRANSP.DIAMOBIL(dg_c, da_c(1 : 3), fl_298), ...
    'sootMosaic:DIAMOBIL:SizeMismatch') && ...
    raises_error(@() TRANSP.CONTINUUM_DM(n_c2(1 : 3), dg_c, [], 'eq17'), ...
    'sootMosaic:CONTINUUM_DM:SizeMismatch') && ...
    raises_error(@() TRANSP.CONTINUUM_DM([2; 1], [1; 1], 1, 'backbone'), ...
    'sootMosaic:CONTINUUM_DM:SizeMismatch') && ...
    raises_error(@() TRANSP.CONTINUUM_DM([2; 1], [1; 1], [1; 1; 1], ...
    'backbone'), 'sootMosaic:CONTINUUM_DM:SizeMismatch');
[names, pass] = add(names, pass, ...
    'rows and columns give the same diameters, unequal lengths stop', ...
    ok_rc && all(ref_b > 0) && ref_b(1) == 30e-9);
[names, pass] = add(names, pass, 'DIAMOBIL rejects unknown names', ...
    raises_error(@() TRANSP.DIAMOBIL(1e-8, 1e-8, room, kim, ...
    struct('continuum', 'mixed')), ...
    'sootMosaic:DIAMOBIL:UnknownContinuumDiameter') && ...
    raises_error(@() TRANSP.DIAMOBIL(1e-8, 1e-8, room, kim, ...
    struct('root', 'newton')), 'sootMosaic:DIAMOBIL:UnknownRootSolve') && ...
    raises_error(@() TRANSP.DIAMOBIL(1e-8, 1e-8, room, kim, ...
    struct('continuum', 'sorensen_backbone')), ...
    'sootMosaic:DIAMOBIL:MissingPrimaryData'));

% model profiles
m1 = UTILS.MODEL_PROFILE('article1_7658971', 'LD1');
m2 = UTILS.MODEL_PROFILE('article1_7658971', 'LD2');
m3 = UTILS.MODEL_PROFILE('current', 'LD1');
[m4, known] = UTILS.MODEL_PROFILE('current', 'LD2');
[names, pass] = add(names, pass, 'profile mobility defaults', ...
    strcmp(m1.mobility, 'sorensen_eq17') && strcmp(m2.mobility, 'interp') && ...
    strcmp(m3.mobility, 'interp') && strcmp(m4.mobility, 'interp') && ...
    strcmp(m1.continuum_diameter, 'fixed_075dg') && ...
    strcmp(m2.continuum_diameter, 'fixed_075dg') && ...
    strcmp(m3.continuum_diameter, 'sorensen_backbone') && ...
    strcmp(m4.continuum_diameter, 'sorensen_backbone') && ...
    strcmp(m1.root_solve, 'start_point_7658971') && ...
    strcmp(m2.root_solve, 'start_point_7658971') && ...
    strcmp(m3.root_solve, 'bracketed') && strcmp(m4.root_solve, 'bracketed') ...
    && isequal(known.mobility, {'sorensen_eq17', 'continuum', ...
    'sorensen_backbone', 'interp', 'free_molecular'}) && ...
    isequal(known.continuum_diameter, {'sorensen_backbone', 'fixed_075dg'}) ...
    && isequal(known.root_solve, {'bracketed', 'start_point_7658971'}));

% loaders
tmp = tempname;
mkdir(tmp);
cleanup = onCleanup(@() rmdir(tmp, 's'));
ld1 = jsondecode(fileread(fullfile(repoRoot, 'config', 'main_ld1', ...
    'main_ld1_config.example.json')));
ld2 = jsondecode(fileread(fullfile(repoRoot, 'config', 'main_ld2', ...
    'main_ld2_from_main_scatter_config.example.json')));
ld2s = jsondecode(fileread(fullfile(repoRoot, 'config', 'main_ld2', ...
    'main_ld2_from_main_scale_config.example.json')));
f1 = @(c) UTILS.LOAD_MAIN_LD1_CONFIG(write_config(tmp, c));
f2 = @(c) UTILS.LOAD_MAIN_LD2_CONFIG(write_config(tmp, c));
ld1_c = ld1;
ld1_c.transport.mobility_options.mtd = 'continuum'; % earlier name
c1 = quiet(@() f1(ld1_c));
c2 = quiet(@() f2(ld2));
c3 = quiet(@() f2(ld2s));
[names, pass] = add(names, pass, ...
    'example configs resolve and save the mobility options', ...
    strcmp(c1.transport.mobility_options.mtd, 'continuum') && ...
    strcmp(c1.model.mobility, 'sorensen_eq17') && ...
    strcmp(c2.model.mobility, 'interp') && ...
    strcmp(c3.model.mobility, 'interp') && ...
    all(cellfun(@(c) strcmp(c.model.continuum_diameter, ...
    'sorensen_backbone') && strcmp(c.model.root_solve, 'bracketed') && ...
    strcmp(c.transport.mobility_options.continuum_diameter, ...
    'sorensen_backbone') && ...
    strcmp(c.transport.mobility_options.root_solve, 'bracketed'), ...
    {c1, c2, c3})));
examples = {ld1, ld2, ld2s};
loaders = {f1, f2, f2};
mtd_a1 = {'sorensen_eq17', 'interp', 'interp'};
ok_cur = true;
ok_a1 = true;
ok_bad = true;
stage = {'LD1', 'LD2', 'LD2'};
for i = 1 : 3
    c = examples{i};
    c.transport.mobility_options = rmfield(c.transport.mobility_options, ...
        {'mtd', 'continuum_diameter', 'root_solve'});
    cfg = quiet(@() loaders{i}(c));
    ok_cur = ok_cur && strcmp(cfg.model.mobility, 'interp') && ...
        strcmp(cfg.transport.mobility_options.mtd, 'interp') && ...
        strcmp(cfg.model.continuum_diameter, 'sorensen_backbone') && ...
        strcmp(cfg.model.root_solve, 'bracketed');
    c.model_profile = 'article1_7658971';
    cfg = quiet(@() loaders{i}(c));
    ok_a1 = ok_a1 && strcmp(cfg.model.mobility, mtd_a1{i}) && ...
        strcmp(cfg.model.continuum_diameter, 'fixed_075dg') && ...
        strcmp(cfg.model.root_solve, 'start_point_7658971') && ...
        strcmp(cfg.transport.mobility_options.continuum_diameter, ...
        'fixed_075dg') && strcmp(cfg.transport.mobility_options.root_solve, ...
        'start_point_7658971');
    id = sprintf('sootMosaic:LOAD_MAIN_%s_CONFIG:InvalidChoice', stage{i});
    for fld = {'mtd', 'continuum_diameter', 'root_solve'}
        cb = examples{i};
        cb.transport.mobility_options.(fld{1}) = 'mixed';
        ok_bad = ok_bad && raises_error(@() loaders{i}(cb), id);
    end
end
[names, pass] = add(names, pass, ...
    'current without mobility fields gives interp, backbone and bracketed', ...
    ok_cur);
[names, pass] = add(names, pass, ...
    'article1_7658971 without mobility fields gives the 7658971 options', ...
    ok_a1);
[names, pass] = add(names, pass, ...
    'loaders reject unknown mobility, continuum and root names', ok_bad);

% resume of LD2 checkpoints that advance two transport steps
model_p16 = struct('profile', 'current', 'fluid_properties', 'sutherland', ...
    'slip_correction', kim);
mob = struct('mtd', 'interp', 'c_dt', 1, 'slip', kim);
[ok, out] = resume_checkpoint(fullfile(tmp, 'r1'), model_p16, mob, true);
[names, pass] = add(names, pass, ...
    'resume without mobility options keeps fixed_075dg and start point', ...
    ok && strcmp(out.cfg_ld2.model.mobility, 'interp') && ...
    strcmp(out.cfg_ld2.model.continuum_diameter, 'fixed_075dg') && ...
    strcmp(out.cfg_ld2.model.root_solve, 'start_point_7658971') && ...
    strcmp(out.opts_mobil.continuum_diameter, 'fixed_075dg') && ...
    strcmp(out.opts_mobil.root_solve, 'start_point_7658971') && ...
    advanced(out) && adjusted(out, 0.75 * out.pars_LD2.dg, cc_kim));
model_c = UTILS.MODEL_PROFILE('current', 'LD2');
mob = struct('mtd', 'interp', 'c_dt', 1, 'slip', kim, ...
    'continuum_diameter', 'sorensen_backbone', 'root_solve', 'bracketed');
[ok, out] = resume_checkpoint(fullfile(tmp, 'r2'), model_c, mob, false);
dpp1 = 30e-9 * ones(size(out.pars_LD2.n));
[names, pass] = add(names, pass, ...
    'resume keeps saved mobility options and advances with the backbone', ...
    ok && isequal(out.cfg_ld2.model, model_c) && advanced(out) && ...
    all(out.pars_LD2.dm(out.pars_LD2.n == 1) == 30e-9) && ...
    adjusted(out, TRANSP.CONTINUUM_DM(out.pars_LD2.n, out.pars_LD2.dg, ...
    dpp1, 'backbone'), cc_kim));
[ok, out] = resume_checkpoint(fullfile(tmp, 'r3'), [], ...
    struct('mtd', 'continuum', 'c_dt', 1), false);
[names, pass] = add(names, pass, ...
    'resume without model options records the method of its options', ...
    ok && strcmp(out.cfg_ld2.model.mobility, 'sorensen_eq17') && ...
    strcmp(out.cfg_ld2.model.continuum_diameter, 'fixed_075dg') && ...
    advanced(out) && isequal(out.pars_LD2.dm, 1.29 * ...
    out.pars_LD2.n.^(-0.13) .* out.pars_LD2.dg));
% a run interrupted at its own checkpoint and resumed against the same run...
%     ...uninterrupted, with the 'current' and the 7658971 settings (both...
%     ...draw projected areas with PAR.PROJECTION at every step here)
mob = struct('mtd', 'interp', 'c_dt', 1, 'slip', kim, ...
    'continuum_diameter', 'sorensen_backbone', 'root_solve', 'bracketed');
ok_c = resume_matches_full(fullfile(tmp, 'r4'), model_c, mob);
model_a = UTILS.MODEL_PROFILE('article1_7658971', 'LD2');
mob_a = struct('mtd', 'interp', 'c_dt', 1, 'slip', ...
    model_a.slip_correction, 'continuum_diameter', ...
    model_a.continuum_diameter, 'root_solve', model_a.root_solve);
ok_a = resume_matches_full(fullfile(tmp, 'r5'), model_a, mob_a);
[names, pass] = add(names, pass, ...
    'resumed run equals the uninterrupted run, generator state included', ...
    ok_c && ok_a);

clear cleanup restore_rng
report = struct('name', names, 'pass', num2cell(pass));
for i = 1 : numel(pass)
    if pass(i)
        fprintf('PASS %s\n', names{i});
    else
        fprintf('FAIL %s\n', names{i});
    end
end
if ~all(pass)
    error('sootMosaic:QA:MobilityMethodsFailed', '%d of %d cases failed.', ...
        sum(~pass), numel(pass))
end

end

function [names, pass] = add(names, pass, name, ok)
