function restore_state(state, message, id, primary, fallback)
warning(state);
lastwarn(message, id);
setenv('SOOTMOSAIC_MAIN_TEM_ANALYSIS_CONFIG', primary);
setenv('PFAL_MAIN_TEM_ANALYSIS_CONFIG', fallback);
end
