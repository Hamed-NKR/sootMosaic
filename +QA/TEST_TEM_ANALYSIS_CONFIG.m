function value = put_parts(value, parts, item)
key = parts{1};
if endsWith(key, '[]')
    key = key(1:end - 2);
    items = value.(key);
    if isstruct(items), items = num2cell(items); end
    items{1} = put_parts(items{1}, parts(2:end), item);
    value.(key) = items;
elseif isscalar(parts)
    value.(key) = item;
else
    if ~isfield(value, key), value.(key) = struct(); end
    value.(key) = put_parts(value.(key), parts(2:end), item);
end
end

function value = drop_value(value, path)
value = drop_parts(value, strsplit(path, '.'));
end

function value = drop_parts(value, parts)
key = parts{1};
if endsWith(key, '[]')
    key = key(1:end - 2);
    items = value.(key);
    if isstruct(items), items = num2cell(items); end
    items{1} = drop_parts(items{1}, parts(2:end));
    value.(key) = items;
elseif isscalar(parts)
    if isfield(value, key), value = rmfield(value, key); end
elseif isfield(value, key)
    value.(key) = drop_parts(value.(key), parts(2:end));
end
end

function value = get_value(value, path)
parts = strsplit(path, '.');
for k = 1:numel(parts)
    key = parts{k};
    if endsWith(key, '[]')
        value = value.(key(1:end - 2));
        if iscell(value), value = value{1}; else, value = value(1); end
    else
        value = value.(key);
    end
end
end

