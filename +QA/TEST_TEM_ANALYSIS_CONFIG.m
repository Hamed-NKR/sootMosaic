function report = TEST_TEM_ANALYSIS_CONFIG()
% "TEST_TEM_ANALYSIS_CONFIG" checks TEM analysis task reading.
% ----------------------------------------------------------------------- %
%
% Outputs:
%     report: Structure array with name and pass. Temporary fixtures are...
%         ...removed on exit. Failures raise...
%         ...sootMosaic:QA:TemAnalysisConfigFailed
% ----------------------------------------------------------------------- %

folder = tempname;
[ok, message] = mkdir(folder);
if ~ok, error('sootMosaic:QA:TemAnalysisConfigFailed', '%s', message); end
cleanup = onCleanup(@() rmdir(folder, 's'));
state = warning;
[warn_message, warn_id] = lastwarn;
primary = getenv('SOOTMOSAIC_MAIN_TEM_ANALYSIS_CONFIG');
fallback = getenv('PFAL_MAIN_TEM_ANALYSIS_CONFIG');
restore = onCleanup(@() restore_state(state, warn_message, warn_id, ...
    primary, fallback));
warning('off', 'sootMosaic:CONFIG_READ:UnknownKey');
root = fileparts(fileparts(mfilename('fullpath')));
example = fullfile(root, 'config', 'main_tem_analysis', ...
    'main_tem_analysis_config.example.json');
dictionary = fullfile(root, 'config', 'main_tem_analysis', ...
    'main_tem_analysis.keys.json');
raw = jsondecode(fileread(example));
rows = jsondecode(fileread(dictionary));
if isstruct(rows), rows = num2cell(rows); end
paths = cellfun(@(r) r.path, rows, 'UniformOutput', false);
task_dir = fullfile(folder, 'tasks', 'tem');
mkdir(task_dir);
file = fullfile(task_dir, 'task.json');
strict = struct('Strict', true);
% Working task with a model filter on the first entry
base = raw;
base.entries{1}.model_filter = struct('field', 'da_nm', 'operator', '>', ...
    'value', 1);
figure_list = figure_ids();
first_id = '2024_08_19_low_agglomeration';
second_id = '2025_02_06_high_agglomeration';
tests = {@coverage, @example_forms, @wrapped_inputs, @numeric_inputs, ...
    @logical_inputs, @text_inputs, @optional_inputs, @fallback_sets, ...
    @pass_through, @selectors, @overlays, @invalid_inputs, ...
    @reader_options, @text_array_ids, @legend_arrays, @second_read};
names = {'dictionary coverage both ways', 'example and parent forms', ...
    'native section and whole-task wrappers', ...
    'independent numeric contract', 'logical conversion', ...
    'text conversion and emptiness', 'optional values and defaults', ...
    'figure and bin sets of the loader', ...
    'pass-through, replaced and unknown keys', ...
    'selectors and default file', 'overlays, id merge and provenance', ...
    'invalid values and required keys', 'reader options of this task', ...
    'one-element text arrays as ids in every layer', ...
    'legend arrays without legend keys', ...
    'second read warnings and fallback provenance'};
pass = false(size(tests));
for case_index = 1:numel(tests)
    try
        tests{case_index}();
        pass(case_index) = true;
    catch err
        fprintf('FAIL %s (%s) %s\n', names{case_index}, err.identifier, ...
            err.message);
    end
end
report = struct('name', names(:), 'pass', num2cell(pass(:)));
if ~all(pass)
    error('sootMosaic:QA:TemAnalysisConfigFailed', '%d cases failed.', ...
        sum(~pass));
end

    function cfg = load_value(value, controls)
        if nargin < 2, controls = strict; end
        write_text(file, jsonencode(value));
        cfg = UTILS.LOAD_MAIN_TEM_ANALYSIS_CONFIG(file, controls);
    end

    function cfg = load_text(text, controls)
        if nargin < 2, controls = strict; end
        write_text(file, text);
        cfg = UTILS.LOAD_MAIN_TEM_ANALYSIS_CONFIG(file, controls);
    end

    function cfg = load_null(value, path)
        text = jsonencode(set_value(value, path, 'NULL_TOKEN'));
        cfg = load_text(strrep(text, '"NULL_TOKEN"', 'null'));
    end

    function coverage()
        expected = expected_paths();
        check(isequal(sort(paths(:)), sort(expected(:))));
        check(numel(unique(paths)) == numel(paths));
        types = cellfun(@(r) r.type, rows, 'UniformOutput', false);
        open_paths = paths(strcmp(types, 'any'));
        example_paths = key_paths(raw, '');
        for n = 1:numel(example_paths)
            p = example_paths{n};
            covered = any(strcmp(paths, p)) || any(cellfun( ...
                @(o) startsWith(p, [o '.']), open_paths));
            check(covered);
        end
        [fallback_paths, fallback_modes] = fallback_contract();
        reader_paths = reader_contract();
        check(isequal(sort(reader_paths(:, 1)), sort(expected(:))));
        for n = 1:numel(rows)
            r = rows{n};
            check(all(isfield(r, {'type', 'unit', 'status', 'since', ...
                'reader', 'reading_rule'})) && ~isempty(r.reader) && ...
                ~isempty(r.reading_rule));
            container = any(strcmp(r.type, {'object', 'any', ...
                'list of objects'}));
            check(isfield(r, 'native_json') == container);
            check(isfield(r, 'open') == strcmp(r.type, 'any'));
            check(isfield(r, 'struct_fallback') == ...
                any(strcmp(r.path, struct_fallback_paths())));
            legend_row = endsWith(r.path, '.legend');
            check(isfield(r, 'array_fallback') == legend_row);
            check(~legend_row || r.array_fallback);
            id_row = any(strcmp(r.path, strcat(native_items_paths(), '[].id')));
            check(isfield(r, 'id_char') == id_row && (~id_row || r.id_char));
            check(isfield(r, 'native_items') == ...
                any(strcmp(r.path, native_items_paths())));
            match = find(strcmp(fallback_paths, r.path));
            check(isfield(r, 'loader_fallback') == ~isempty(match));
            if ~isempty(match)
                check(strcmp(r.loader_fallback, fallback_modes{match}));
            end
            % Each row names the consumer of the independent reader contract
            check(strcmp(r.reader, reader_paths{strcmp(reader_paths(:, 1), ...
                r.path), 2}));
            readers = strsplit(r.reader, ', ');
            for j = 1:numel(readers)
                code = which(['UTILS.' readers{j}]);
                if isempty(code), code = fullfile(root, [readers{j} '.m']); end
                check(isfile(code));
            end
        end
        % The logical rows equal the independent logical contract
        logical_paths = logical_contract();
        check(numel(logical_paths) == 47 && ...
            numel(unique(logical_paths)) == 47);
        check(isequal(sort(paths(strcmp(types, 'logical'))), ...
            sort(logical_paths)));
        for n = 1:numel(logical_paths)
            r = rows{strcmp(paths, logical_paths{n})};
            check(strcmp(r.type, 'logical') && isfield(r, 'coerce') && ...
                strcmp(r.coerce, 'logical'));
        end
        required = required_paths();
        marked = paths(cellfun(@(r) isfield(r, 'required') && r.required, rows));
        check(isequal(sort(marked(:)), sort(required(:))));
        contract = numeric_contract();
        for n = 1:size(contract, 1)
            r = rows{strcmp(paths, contract{n, 1})};
            check(strcmp(r.type, contract{n, 2}) && strcmp(r.unit, contract{n, 3}));
            check(isfield(r, 'coerce') && strcmp(r.coerce, 'double'));
            check(isequal(row_field(r, 'min'), contract{n, 4}));
            check(isequal(row_field(r, 'max'), contract{n, 5}));
            reshaped = ~isempty(regexp(contract{n, 2}, 'vector|numbers', 'once'));
            check(isequal(isfield(r, 'row_vector') && r.row_vector, reshaped));
        end
        numeric = paths(~cellfun(@isempty, regexp(types, ...
            '^(number|integer|integer or empty|vector|\d+ numbers)$', 'once')));
        check(isequal(sort(numeric(:)), sort([{'config_version'}; contract(:, 1)])));
        defaults = default_contract();
        defaulted = paths(cellfun(@(r) isfield(r, 'default'), rows));
        check(isequal(sort(defaulted(:)), sort(defaults(:, 1))));
        for n = 1:size(defaults, 1)
            r = rows{strcmp(paths, defaults{n, 1})};
            value = r.default;
            if isnumeric(value) && ~isempty(value), value = value(:).'; end
            check(isequaln(value, defaults{n, 2}));
        end
    end

    function example_forms()
