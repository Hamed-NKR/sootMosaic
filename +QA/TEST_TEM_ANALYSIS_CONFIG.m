        check(cfg.config_version == 1 && ~isfield(cfg, 'model_profile'));
        check(isstruct(cfg.entries) && isequal(size(cfg.entries), [2 1]));
        check(isequal({cfg.entries.id}, {first_id, second_id}));
        check(strcmp(cfg.config_file, file));
        check(strcmp(cfg.outputs.data_root, ...
            canonical(fullfile(folder, 'data', 'main_tem_analysis'))));
        check(strcmp(cfg.entries(1).aggregate.file, canonical(fullfile( ...
            folder, 'data', 'tem_analysis', '2024-08-19_low_agglomeration', ...
            'atems_aggregate_metrics', '19AUG24_LAL_End_Slider.mat'))));
        check(isequal(cfg.entries(1).aggregate_ids, (1:64).'));
        check(isequal(cfg.entries(1).primary_particle_aggregate_ids, (1:64).'));
        check(isequal(cfg.entries(2).primary_particle_aggregate_ids, ...
            [1 5 9 10 12 13 14 15 16 17 18 21 22 25 29].'));
        check(isequal(size(cfg.plots.frequency_bins.hybridity), [5 1]));
        check(isequal([cfg.plots.frequency_bins.hybridity.upper], ...
            [1 2 5 10 Inf]));
        categories = cfg.plots.figures.dpp_vs_da_by_hybridity.categories;
        check(isequal(size(categories), [4 1]) && ...
            isequal([categories.lower], [1 2 3 5]));
        check(isequal(cfg.plots.figures.dpp_vs_da_manual_tem.legend, ...
            struct('location', 'eastoutside', 'orientation', 'vertical', ...
            'columns', 1, 'box', false, 'interpreter', 'tex')));
        arrows = cfg.plots.figures.subaggregate_count_frequencies.arrows;
        check(isequal(arrows.condition_ids, {first_id; second_id}) && ...
            arrows.shaft_length == 7 && arrows.target_bin_index == 1);
        check(isequal(cfg.plots.figures.dpp_vs_da_manual_tem.arrows, struct()));
        check(isequal(cfg.plots.figures.primary_particle_distributions.grid, ...
            struct()));
        check(isequal(cfg.plots.figures.aggregate_metric_distributions.categories, ...
            struct([])));
        check(cfg.plots.pdf && cfg.plots.png && cfg.plots.png_resolution == 600);
        check(isequal(size(cfg.entries(2).style.stack_colors.hybridity), [5 1]));
        check(isequal(cfg.entries(1).model_filter, struct()));
        check(isequal(cfg.analysis.random_seed, 1));
        task = rmfield(cfg, {'si', 'provenance'});
        check(isequal(cfg.si, task));
        check(isscalar(cfg.provenance.files) && endsWith( ...
            cfg.provenance.dictionary.file, 'main_tem_analysis.keys.json'));
        saved = jsondecode(jsonencode(cfg));
        check(isfield(saved, 'si') && isfield(saved, 'provenance'));
        % Parent form without config_version
        cfg_old = load_value(rmfield(raw, 'config_version'));
        check(cfg_old.config_version == 1);
        check(isequaln(without_records(cfg_old), without_records(cfg)));
    end

    function wrapped_inputs()
        ordinary = without_records(load_value(base));
        objects = {'analysis', 'analysis.summary', 'outputs', 'plots', ...
            'plots.axes', 'plots.boxplot', 'plots.font', 'plots.reference', ...
            'plots.frequency_bins', 'plots.figures'};
        for n = 1:numel(figure_list)
            objects{end + 1} = ['plots.figures.' figure_list{n}]; %#ok<AGROW>
            objects{end + 1} = ['plots.figures.' figure_list{n} '.legend']; %#ok<AGROW>
        end
        objects = [objects, {'plots.figures.subaggregate_count_distribution.grid', ...
            'plots.figures.subaggregate_count_distribution.zero_line', ...
            'plots.figures.subaggregate_count_frequencies.arrows'}];
        for n = 1:numel(objects)
            if ~has_value(base, objects{n}), continue; end
            value = set_value(base, objects{n}, {get_value(base, objects{n})});
            check(isequaln(without_records(load_value(value)), ordinary));
        end
        for key = {'aggregate', 'primary_particles', 'style', ...
                'style.stack_colors', 'model_filter'}
            value = set_value(base, ['entries[].' key{1}], ...
                {get_value(base, ['entries[].' key{1}])});
            check(isequaln(without_records(load_value(value)), ordinary));
        end
        cfg = load_text(['[' jsonencode(base) ']']);
        check(isequaln(without_records(cfg), ordinary));
        % One entry, one bin set and one category as objects
        value = second_only(base);
        value.entries = base.entries{2};
        single = without_records(load_value(value));
        value.entries = base.entries(2);
        check(isequaln(without_records(load_value(value)), single));
        check(isequal(size(single.entries), [1 1]) && ...
            strcmp(single.entries.id, second_id));
        value = base;
        value.plots.figures.dpp_vs_da_by_hybridity.categories = ...
            base.plots.figures.dpp_vs_da_by_hybridity.categories(1);
        cfg = load_value(value);
        check(isequal(size(cfg.plots.figures.dpp_vs_da_by_hybridity.categories), ...
            [1 1]));
    end

    function numeric_inputs()
        contract = numeric_contract();
        % Every contract row in one task, for each input form
        for form = {'plain', 'array', 'code', 'column'}
            value = base;
            for n = 1:size(contract, 1)
                value = set_value(value, contract{n, 1}, ...
                    numeric_form(contract(n, :), form{1}));
            end
            cfg = load_value(value);
            for n = 1:size(contract, 1)
                actual = get_value(cfg, contract{n, 1});
                check(isa(actual, 'double') && isequal(actual, contract{n, 6}));
                check(isequal(get_value(cfg.si, contract{n, 1}), contract{n, 6}));
            end
        end
        % Refusals on the rows outside the figures, the first figure and...
            % ...the figure-specific rows
        for n = 1:size(contract, 1)
            target = contract{n, 1};
            if ~refused_row(target), continue; end
            valid = contract{n, 6};
            type = contract{n, 2};
            if any(strcmp(type, {'number', 'integer', 'integer or empty'}))
                fails(@() load_value(set_value(base, target, 'ab')), ...
                    'sootMosaic:CONFIG_READ:InvalidType');
            end
            if ~isempty(contract{n, 4})
                fails(@() load_value(set_value(base, target, ...
                    contract{n, 4} - 1 + 0 * valid)), ...
                    'sootMosaic:CONFIG_READ:OutOfRange');
            end
            if ~isempty(contract{n, 5})
                fails(@() load_value(set_value(base, target, ...
                    contract{n, 5} + 1)), 'sootMosaic:CONFIG_READ:OutOfRange');
            end
            if any(strcmp(type, {'integer', 'integer or empty'}))
                fails(@() load_value(set_value(base, target, valid + 0.5)), ...
                    'sootMosaic:CONFIG_READ:InvalidInteger');
            end
            if any(strcmp(type, {'2 numbers', '4 numbers'}))
                fails(@() load_value(set_value(base, target, valid(1))), ...
                    'sootMosaic:CONFIG_READ:InvalidType');
                fails(@() load_value(set_value(base, target, [valid valid])), ...
                    'sootMosaic:CONFIG_READ:InvalidLength');
            end
        end
        % Logical, matrix and text inputs follow the double conversion
        value = set_value(base, 'plots.axis_line_width', true);
        value = set_value(value, ...
            'plots.figures.dpp_vs_da_manual_tem.position', [true false true true]);
        value = set_value(value, ...
            'plots.figures.subaggregate_count_distribution.y_ticks', [1 3; 2 4]);
        value = set_value(value, ...
            'plots.figures.primary_particle_distributions.x_limits', 'AB');
        value = set_value(value, 'analysis.random_seed', '');
        cfg = load_value(value);
        figures = cfg.plots.figures;
        check(cfg.plots.axis_line_width == 1 && ...
            isequal(figures.dpp_vs_da_manual_tem.position, [1 0 1 1]) && ...
            isequal(figures.subaggregate_count_distribution.y_ticks, 1:4) && ...
            isequal(figures.primary_particle_distributions.x_limits, [65 66]) && ...
            isequal(cfg.analysis.random_seed, []));
        target = 'plots.figures.primary_particle_distributions.x_limits';
        text = strrep(jsonencode(set_value(base, target, [1 2])), ...
            '"x_limits":[1,2]', '"x_limits":[1,null]');
        fails(@() load_text(text), 'sootMosaic:CONFIG_READ:Nonfinite');
        fails(@() load_value(set_value(base, 'plots.axes.tick_length', ...
            [0.02 -0.01])), 'sootMosaic:CONFIG_READ:OutOfRange');
    end

    function logical_inputs()
        logical_paths = logical_contract();
        harmless = logical_paths(~contains(logical_paths, 'include_') & ...
            ~strcmp(logical_paths, 'plots.pdf'));
        % Every logical row in one task, for each true form
        for item = {true, 1, 3, {true}}
            value = base;
            for n = 1:numel(logical_paths)
                value = set_value(value, logical_paths{n}, item{1});
            end
            cfg = load_value(value);
            for n = 1:numel(logical_paths)
                actual = get_value(cfg, logical_paths{n});
                check(islogical(actual) && isscalar(actual) && actual);
            end
        end
        value = base;
        for n = 1:numel(harmless)
            value = set_value(value, harmless{n}, 0);
        end
        cfg = load_value(value);
        for n = 1:numel(harmless)
            actual = get_value(cfg, harmless{n});
            check(islogical(actual) && isscalar(actual) && ~actual);
        end
        for target = {'plots.save_figures', 'entries[].include_in_model_inputs', ...
                'plots.frequency_bins.collapse[].include_upper', ...
                'plots.figures.subaggregate_count_distribution.grid.y_minor'}
            fails(@() load_value(set_value(base, target{1}, [true false])), ...
                'sootMosaic:CONFIG_READ:InvalidType');
        end
        for target = {'plots.enabled', 'plots.export', ...
                'plots.frequency_bins.hybridity[].include_lower', ...
                'plots.figures.dpp_vs_da_manual_tem.enabled'}
            fails(@() load_value(set_value(base, target{1}, [])), ...
                'sootMosaic:CONFIG_READ:InvalidType');
        end
    end

