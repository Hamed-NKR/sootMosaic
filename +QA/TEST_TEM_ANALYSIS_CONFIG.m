warning('off', 'backtrace');
captured = evalc('action();');
count = numel(strfind(captured, message));
clear restore
end

function item = numeric_form(row, form)
% Writing a valid contract value as a plain value, a one-element array,...
    % ...a character code or a column of one-element arrays
item = row{6};
scalar = any(strcmp(row{2}, {'number', 'integer', 'integer or empty'}));
switch form
    case 'array'
        item = {item};
    case 'code'
        if scalar && item == fix(item) && item >= 1 && item < 128
            item = char(item);
        end
    case 'column'
        if ~scalar
            item = cellfun(@(x) {x}, num2cell(item(:)), 'UniformOutput', false);
        end
end
end

