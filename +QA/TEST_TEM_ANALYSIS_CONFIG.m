function fails(action, expected)
caught = false;
try
    action();
catch err
    caught = strcmp(err.identifier, expected);
    if ~caught
        error('sootMosaic:QA:TemAnalysisConfigFailed', ...
            'Expected %s; received %s (%s).', expected, err.identifier, ...
            err.message);
    end
end
check(caught);
end

function paths = key_paths(value, prefix)
paths = cell(0, 1);
if iscell(value) && all(cellfun(@isstruct, value(:)))
    value = cellfun(@(entry) key_paths(entry, prefix), value(:), ...
        'UniformOutput', false);
    paths = unique(vertcat(value{:}));
    return
end
if ~isstruct(value), return; end
if ~isscalar(value)
    groups = arrayfun(@(entry) key_paths(entry, prefix), value(:), ...
        'UniformOutput', false);
    paths = unique(vertcat(groups{:}));
    return
end
names = fieldnames(value);
groups = cell(numel(names), 1);
for k = 1:numel(names)
    if isempty(prefix)
        child_path = names{k};
    else
        child_path = [prefix '.' names{k}];
    end
    item = value.(names{k});
    if (isstruct(item) && ~isscalar(item)) || ...
            (iscell(item) && ~isempty(item) && all(cellfun(@isstruct, item(:))))
        groups{k} = [{child_path}; key_paths(item, [child_path '[]'])];
    else
        groups{k} = [{child_path}; key_paths(item, child_path)];
    end
end
if ~isempty(groups), paths = vertcat(groups{:}); end
end

