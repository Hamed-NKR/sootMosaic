    function optional_inputs()
        defaults = default_contract();
        skipped = {'config_version', 'analysis.summary', 'plots.axes', ...
            'plots.boxplot', 'plots.font', 'plots.reference', ...
            'plots.figures.subaggregate_count_distribution.grid', ...
            'plots.figures.subaggregate_count_distribution.zero_line', ...
            'plots.figures.dpp_vs_da_by_hybridity.categories[].line_width'};
        keep = ~ismember(defaults(:, 1), skipped);
        defaults = defaults(keep, :);
        % Every defaulted key empty, null or absent in one task
        for item = {[], '', 'NULL_TOKEN', 'ABSENT_TOKEN'}
            value = base;
            for n = 1:size(defaults, 1)
                if isequal(item{1}, 'ABSENT_TOKEN')
                    value = drop_value(value, defaults{n, 1});
                else
                    value = set_value(value, defaults{n, 1}, item{1});
                end
            end
            text = strrep(jsonencode(value), '"NULL_TOKEN"', 'null');
            cfg = load_text(text);
            for n = 1:size(defaults, 1)
                actual = get_value(cfg, defaults{n, 1});
                expected = defaults{n, 2};
                check(isequaln(actual, expected) && ...
                    isequal(size(actual), size(expected)));
            end
        end
        target = 'plots.figures.dpp_vs_da_by_hybridity.categories[].line_width';
        check(get_value(load_value(drop_value(base, target)), target) == 1.5);
        % Object defaults fill every child
        objects = { ...
            'analysis.summary', struct('confidence_level', 0.95, ...
            'morphology_center', 'median', 'morphology_spread', 'iqr', ...
            'morphology_interval', 'bootstrap_percentile', ...
            'frequency_interval', 'wilson'); ...
            'plots.axes', struct('box', true, 'layer', 'top', ...
            'tick_length', [0.02 0.02], 'tick_label_rotation', 0, ...
            'label_position_mode', 'auto', 'x_label_offset', 0.055, ...
